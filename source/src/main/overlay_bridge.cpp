// overlay_bridge.cpp — bridge BAR's "uv" module loader to librecomp overlay registration.
//
// BAR loads each relocatable module into a heap buffer and jumps to its entry point
// (decomp src/module.c: uvLoadModuleCode -> uvDoModuleRelocs -> entryPointFunction(...)). In a
// static recomp the module's recompiled functions live in func_map keyed by their recomp-ELF VRAM
// (0x80800000 + id*0x100000), NOT the heap address — so the entry-point LOOKUP_FUNC failed with
// "Failed to find function at 0x...".
//
// Fix: intercept uvDoModuleRelocs (called with a0 = ovlStartPtr, a1 = ModuleCommInfo*, right before
// the entry jump) and register the module's section at ovlStartPtr via load_overlay_by_id() before
// running the original relocation. scripts/fix-recompiled.sh renames the generated definition to
// uvDoModuleRelocs_orig so this wrapper owns the `uvDoModuleRelocs` symbol that all callers bind to.
//
// The module is identified by its 4-char nameTag (ModuleCommInfo.nameTag, offset 0x1C). The
// nameTag -> overlay_id table below is in overlays.us.txt order (overlay_id 0 = .ai ... 132 =
// .weapon). The authoritative module-name -> tag mapping is the decomp's
// tools/convPartialModule.py `partial_to_module` dict; this table was generated by joining it with
// overlays.us.txt. overlay_id indexes recomp's overlay_sections_by_index[] (recomp_overlays.inl).
#include <cstdio>
#include <cstdint>
#include <cstdlib>   // std::getenv (BAR_DEBUG_OVERLAYS gate)

#include "recomp.h"   // recomp_context, gpr, MEM_W

extern "C" void __entrypoint_func_race_400000__race_orig(uint8_t*, recomp_context*);
extern "C" void func_plyr_00400678__race_orig(uint8_t*, recomp_context*);
extern "C" void func_scrn_0040009C__race_orig(uint8_t*, recomp_context*);
static thread_local bool extended_race_setup=false;
static thread_local bool race_test_running=false;
static thread_local unsigned race_ticks[4]{};
extern "C" void func_plyr_00401484__race_orig(uint8_t*, recomp_context*);
extern "C" void func_uvcont_rom_00400678__race_orig(uint8_t*, recomp_context*);
extern "C" void func_selection_00402F30__race_orig(uint8_t*, recomp_context*);

static const char* race_experiment() {
    const char* value=std::getenv("BAR_RACE_PLAYERS");
    if ((!value || !*value) && std::getenv("BAR_BACKGROUND_TEST"))
        value=std::getenv("BAR_TEST_RACE_PLAYERS");
    if (!value) return nullptr;
    char* end=nullptr; const long count=std::strtol(value,&end,10);
    return end && !*end && count>=2 && count<=4 ? value : nullptr;
}

extern "C" void func_selection_00402F30(uint8_t* rdram, recomp_context* ctx) {
    // Let selection finish its current-player teardown before changing its loop bound.
    // The engine loads the next scene only after this callback returns.
    func_selection_00402F30__race_orig(rdram,ctx);
    const char* experiment=race_experiment();
    if (experiment) {
        char* end=nullptr; const long count=std::strtol(experiment,&end,10);
        const int previous=MEM_W(0,S32(0x80025D14));
        if (end && !*end && count>=2 && count<=4 && previous>=1 && previous<=4) {
            for(int i=previous;i<count;++i) {
                MEM_H(0,S32(0x80025E28+i*6))=MEM_H(0,S32(0x80025E28));
                MEM_H(0,S32(0x80025E2A+i*6))=MEM_H(0,S32(0x80025E2A));
                MEM_B(0,S32(0x80025E2C+i*6))=MEM_B(0,S32(0x80025E2C));
            }
            MEM_W(0,S32(0x80025D14))=int(count);
            MEM_W(0,S32(0x80025D18))=0;
            std::fprintf(stderr,"[race-test] selection launch humans=%ld previous=%d\n",count,previous);
            std::fflush(stderr);
        }
    }
}

extern "C" void func_plyr_00401484(uint8_t* rdram, recomp_context* ctx) {
    const int slot=race_test_running ? MEM_W(0x14,ctx->r4) : -1;
    func_plyr_00401484__race_orig(rdram,ctx);
    if (slot>=0 && slot<4 && ++race_ticks[slot]==120) {
        std::fprintf(stderr,"[race-test] updated slot=%d ticks=120\n",slot);
        std::fflush(stderr);
    }
}

extern "C" void func_uvcont_rom_00400678(uint8_t* rdram, recomp_context* ctx) {
    const int slot=int(ctx->r4);
    func_uvcont_rom_00400678__race_orig(rdram,ctx);
    static thread_local bool seen[4]{};
    if (race_test_running && slot>=0 && slot<4 && ctx->r2 && !seen[slot]) {
        seen[slot]=true;
        std::fprintf(stderr,"[race-test] game controller slot=%d buttons=0x%04X\n",slot,unsigned(ctx->r2)&0xffff);
        std::fflush(stderr);
    }
}

extern "C" void func_scrn_0040009C(uint8_t* rdram, recomp_context* ctx) {
    if (extended_race_setup) {
        const int count=MEM_W(0,S32(0x80025D14));
        if (count>=2 && count<=4) {
            ctx->r4=count; // scrn layout table: 2=two, 3=three, 4=four camera channels.
            std::fprintf(stderr,"[race-test] screen layout=%d\n",count);
        }
    }
    func_scrn_0040009C__race_orig(rdram,ctx);
}

extern "C" void __entrypoint_func_race_400000(uint8_t* rdram, recomp_context* ctx) {
    const char* experiment=race_experiment();
    if (experiment) {
        char* end=nullptr; long count=std::strtol(experiment,&end,10);
        // Four is the CURRENT settings/player-array capacity, not the target grid limit.
        if (end && !*end && count>=2 && count<=4) {
            const int old=MEM_W(0,S32(0x80025D14));
            MEM_W(0,S32(0x80025D14))=int(count);
            // Keep AI disabled for this first human-spawn experiment; mixing follows separately.
            MEM_W(0,S32(0x80025D18))=0;
            for (int i=old;i<count;++i) {
                MEM_H(0,S32(0x80025E28+i*6))=MEM_H(0,S32(0x80025E28));
                MEM_H(0,S32(0x80025E2A+i*6))=MEM_H(0,S32(0x80025E2A));
                MEM_B(0,S32(0x80025E2C+i*6))=MEM_B(0,S32(0x80025E2C));
            }
            std::fprintf(stderr,"[race-test] race entry humans=%ld previous=%d ai=0 state=%d track=%d\n",
                count,old,MEM_W(0,S32(0x80025D94)),MEM_W(0,S32(0x80025D34)));
        }
    }
    extended_race_setup=experiment!=nullptr;
    race_test_running=false;
    for(auto& ticks:race_ticks)ticks=0;
    __entrypoint_func_race_400000__race_orig(rdram,ctx);
    extended_race_setup=false;
    race_test_running=std::getenv("BAR_BACKGROUND_TEST")!=nullptr;
    if (std::getenv("BAR_BACKGROUND_TEST")) {
        std::fprintf(stderr,"[race-test] race entry returned humans=%d\n",MEM_W(0,S32(0x80025D14)));
        std::fflush(stderr);
    }
}

extern "C" void func_plyr_00400678(uint8_t* rdram, recomp_context* ctx) {
    const int slot=int(ctx->r4);
    if (std::getenv("BAR_BACKGROUND_TEST") && slot>=0 && slot<4) {
        const gpr exports=S32(MEM_W(0,S32(0x80025C84)));
        const gpr scene=S32(MEM_W(0x2C,exports));
        const gpr descriptors=S32(MEM_W(0x24,scene));
        const gpr descriptor=ADD32(descriptors,slot*16);
        std::fprintf(stderr,"[race-test] spawn descriptor slot=%d address=0x%08X words=%08X,%08X,%08X,%08X\n",
            slot,uint32_t(descriptor),uint32_t(MEM_W(0,descriptor)),uint32_t(MEM_W(4,descriptor)),
            uint32_t(MEM_W(8,descriptor)),uint32_t(MEM_W(12,descriptor)));
    }
    func_plyr_00400678__race_orig(rdram,ctx);
    if (std::getenv("BAR_BACKGROUND_TEST")) {
        const uint32_t player=uint32_t(ctx->r2);
        std::fprintf(stderr,"[race-test] spawned slot=%d player=0x%08X\n",slot,player);
        const gpr camera=S32(MEM_W(0xC,S32(player)));
        std::fprintf(stderr,"[race-test] camera slot=%d address=0x%08X channel=%d bounds=%d,%d,%d,%d\n",
            slot,uint32_t(camera),MEM_H(0,camera),MEM_H(4,camera),MEM_H(6,camera),MEM_H(8,camera),MEM_H(10,camera));
        std::fflush(stderr);
    }
}

