extern "C" void uvDoModuleRelocs(uint8_t* rdram, recomp_context* ctx) {
    const gpr ovl_start = ctx->r4;                       // a0: where the module CODE was loaded
    const gpr info_addr = ctx->r5;                       // a1: ModuleCommInfo*
    const uint32_t name_tag = (uint32_t)MEM_W(0x1C, info_addr);   // ModuleCommInfo.nameTag

    const int overlay_id = overlay_id_for_tag(name_tag);
    if (overlay_id >= 0) {
        // Register the module's recompiled section at its load address. The section base is the code
        // start (ovlStartPtr) — confirmed by experiment (registering at ovlStartPtr-exportsSize breaks
        // function resolution). unload first so a re-load / address reuse re-registers cleanly.
        unload_overlay_by_id((uint32_t)overlay_id);
        load_overlay_by_id((uint32_t)overlay_id, (uint32_t)ovl_start);
        // Overlays stream continuously during a race; this per-load log is a perf/spam drag, so gate
        // it behind BAR_DEBUG_OVERLAYS (off by default). The unknown-tag WARN below stays unconditional.
        static const bool dbg_overlays = std::getenv("BAR_DEBUG_OVERLAYS") != nullptr;
        if (dbg_overlays) {
            std::fprintf(stderr, "[beetle-adventure-racing-recomp] overlay '%c%c%c%c' (id %d) -> 0x%08X\n",
                (char)(name_tag >> 24), (char)(name_tag >> 16), (char)(name_tag >> 8), (char)name_tag,
                overlay_id, (uint32_t)ovl_start);
        }
    } else {
        std::fprintf(stderr, "[beetle-adventure-racing-recomp] WARN: unknown module nameTag '%c%c%c%c' (0x%08X) @ 0x%08X — not registered\n",
            (char)(name_tag >> 24), (char)(name_tag >> 16), (char)(name_tag >> 8), (char)name_tag,
            name_tag, (uint32_t)ovl_start);
    }

    // Run the game's actual byte relocation (fixes data pointers the recompiled code reads).
    uvDoModuleRelocs_orig(rdram, ctx);
}
